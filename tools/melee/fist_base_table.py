"""Generates plugin/UTPP/src/mm/MeleeBaseData.cpp: per body, one row per frame of every fists clip that ships in the melee archive.

A row = the local rotations of the 13 'key' bones (neck, head, both clavicles and arm chains, Spine1..Spine3) that the game plays from the
clip, plus the clip's Spine3 orientation in model space (the chest as authored, on the clip's own hips and spine). The DLL
(mm/MeleeBase.hpp) recognises the playing clip frame from the key bones and rotates the chest of the live pose back to the
authored orientation, so a punch keeps its direction on the hips / spine the game really shows.

usage: python -I fist_base_table.py [--clips-in DIR] [--out FILE]
Inputs: <clips-in>/pwa_fists__*.npc1.npz (Female V) and pma_fists__*.npc1.npz (Male V): the exact inputs of the shipped archive
(default <project>/Build/work/fists-heavy-punch-20261113/pack/input; regenerating with the defaults reproduces
plugin/UTPP/src/mm/MeleeBaseData.cpp byte for byte). Arrays used: names152 + lr (local rotations), names + W (model matrices, metres).
"""
import argparse
import glob
import hashlib
import os
import sys

import numpy as np

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), '..'))
from utpp_paths import project_root  # noqa: E402

KEYS = ['Neck', 'Head', 'RightShoulder', 'RightArm', 'RightForeArm', 'RightHand', 'LeftShoulder', 'LeftArm', 'LeftForeArm', 'LeftHand', 'Spine1', 'Spine2', 'Spine3']
# clips whose lower body / trunk is not the standing guard family: the game shows them on sprint / crouch / slide / air bases that the
# mod owns (they stay as they are)
EXCLUDE_PREFIXES = ('melee_crouch', 'melee_idle_to_crouch', 'melee_slide', 'melee_sprint', 'melee_air_sprint', 'melee_groundslam',
                    'crouch_attack', 'sprint_attack', 'hold_start_offscreen')
BODIES = (('Female', 'pwa_fists'), ('Male', 'pma_fists'))
DEFAULT_IN = os.path.join(project_root(), 'Build', 'work', 'fists-heavy-punch-20261113', 'pack', 'input')
DEFAULT_OUT = os.path.join(os.path.dirname(__file__), '..', '..', 'plugin', 'UTPP', 'src', 'mm', 'MeleeBaseData.cpp')


def quat_from_matrix(m):
    """3x3 rotation -> unit quaternion xyzw, w >= 0"""
    t = m[0, 0] + m[1, 1] + m[2, 2]
    if t > 0:
        s = np.sqrt(t + 1.0) * 2
        q = [(m[2, 1] - m[1, 2]) / s, (m[0, 2] - m[2, 0]) / s, (m[1, 0] - m[0, 1]) / s, 0.25 * s]
    elif m[0, 0] > m[1, 1] and m[0, 0] > m[2, 2]:
        s = np.sqrt(1.0 + m[0, 0] - m[1, 1] - m[2, 2]) * 2
        q = [0.25 * s, (m[0, 1] + m[1, 0]) / s, (m[0, 2] + m[2, 0]) / s, (m[2, 1] - m[1, 2]) / s]
    elif m[1, 1] > m[2, 2]:
        s = np.sqrt(1.0 + m[1, 1] - m[0, 0] - m[2, 2]) * 2
        q = [(m[0, 1] + m[1, 0]) / s, 0.25 * s, (m[1, 2] + m[2, 1]) / s, (m[0, 2] - m[2, 0]) / s]
    else:
        s = np.sqrt(1.0 + m[2, 2] - m[0, 0] - m[1, 1]) * 2
        q = [(m[0, 2] + m[2, 0]) / s, (m[1, 2] + m[2, 1]) / s, 0.25 * s, (m[1, 0] - m[0, 1]) / s]
    q = np.array(q, dtype=np.float64)
    q /= np.linalg.norm(q)
    return q if q[3] >= 0 else -q


def enc(q):
    q = np.asarray(q, dtype=np.float64)
    q = q / np.linalg.norm(q)
    if q[3] < 0:
        q = -q
    return [int(round(v * 32767.0)) for v in q]


def build(clips_in):
    out = {}
    digests = []
    for body, prefix in BODIES:
        rows, clip_of, names = [], [], []
        for f in sorted(glob.glob(os.path.join(clips_in, prefix + '__*.npz'))):
            nm = os.path.basename(f).split('__')[1].split('.')[0]
            if nm.startswith(EXCLUDE_PREFIXES):
                continue
            with open(f, 'rb') as fh:
                digests.append((os.path.basename(f), hashlib.sha256(fh.read()).hexdigest()))
            z = np.load(f, allow_pickle=True)
            n152, n73 = list(z['names152']), list(z['names'])
            lr, W = z['lr'].astype(np.float64), z['W'].astype(np.float64)
            cid = len(names)
            names.append(nm)
            for i in range(lr.shape[0]):
                row = []
                for k in KEYS:
                    row += enc(lr[i, n152.index(k)])
                row += enc(quat_from_matrix(W[i, n73.index('Spine3'), :3, :3]))
                rows.append(row)
                clip_of.append(cid)
        out[body] = (np.array(rows, dtype=np.int16), np.array(clip_of, dtype=np.uint8), names)
    return out, digests


def emit(out, digests, path):
    L = []
    L.append('// GENERATED by tools/melee/fist_base_table.py - do not edit. Inputs (SHA-256 of the clip files):')
    for n, h in digests:
        L.append('//   %s  %s' % (h[:16], n))
    L.append('#include "MeleeBaseData.hpp"')
    L.append('')
    L.append('namespace utpp::mm::meleebase')
    L.append('{')
    L.append('namespace')
    L.append('{')
    for body, (rows, clip_of, names) in out.items():
        L.append('const int16_t k%sFrames[%d] = {' % (body, rows.size))
        for r in rows:
            L.append(','.join(str(int(v)) for v in r) + ',')
        L.append('};')
        L.append('const uint8_t k%sClipOf[%d] = {%s};' % (body, len(clip_of), ','.join(str(int(v)) for v in clip_of)))
        L.append('const char* const k%sClipNames[%d] = {%s};' % (body, len(names), ','.join('"%s"' % n for n in names)))
        L.append('const TableData k%sTable = {k%sFrames, %du, k%sClipOf, %du, k%sClipNames};' % (body, body, len(rows), body, len(names), body))
    L.append('} // namespace')
    L.append('')
    for body in out:
        L.append('const TableData& %sTable() { return k%sTable; }' % (body, body))
    L.append('} // namespace utpp::mm::meleebase')
    with open(path, 'w', newline='\n') as fh:
        fh.write('\n'.join(L) + '\n')


if __name__ == '__main__':
    ap = argparse.ArgumentParser()
    ap.add_argument('--clips-in', default=DEFAULT_IN)
    ap.add_argument('--out', default=DEFAULT_OUT)
    a = ap.parse_args()
    out, digests = build(os.path.abspath(a.clips_in))
    emit(out, digests, os.path.abspath(a.out))
    for body, (rows, clip_of, names) in out.items():
        print(body, 'clips', len(names), 'frames', rows.shape[0])
    print('wrote', os.path.abspath(a.out), os.path.getsize(os.path.abspath(a.out)), 'bytes')
