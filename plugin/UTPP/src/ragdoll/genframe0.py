# Regenerates GetUpFrame0.hpp (next to this script) from the retargeted motion set3 get-up clips (project
# folder Animations\retarget). Usage: python -I genframe0.py
# Reads Animations\retarget\out_sourcepack_{woman,man}_knee\M_Neutral_GetUp_{Back,Front}.utppclip.json (frame 0, first 7 values per bone).
import json, hashlib, os, sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "..", "..", "tools"))
from utpp_paths import project_root

root = os.path.join(str(project_root()), "Animations", "retarget")
srcs = {
    "woman": {"Back": root + r"\out_sourcepack_woman_knee\M_Neutral_GetUp_Back.utppclip.json",
              "Front": root + r"\out_sourcepack_woman_knee\M_Neutral_GetUp_Front.utppclip.json"},
    "man": {"Back": root + r"\out_sourcepack_man_knee\M_Neutral_GetUp_Back.utppclip.json",
            "Front": root + r"\out_sourcepack_man_knee\M_Neutral_GetUp_Front.utppclip.json"},
}
names = None
tables = {}
digests = []
for body, d in srcs.items():
    for which, path in d.items():
        j = json.load(open(path))
        if names is None:
            names = j["bone_names"]
        assert j["bone_names"] == names, (body, which)
        f0 = j["frames"][0]["bones"]
        assert len(f0) == len(names)
        tables[(body, which)] = [v[:7] for v in f0]
        digests.append("%s/%s sha256 %s" % (body, which, hashlib.sha256(open(path, "rb").read()).hexdigest()[:16]))
        print(body, which, j["num_frames"], "hips", f0[2][:3])


def fl(v):
    t = "%.9g" % v
    if "." not in t and "e" not in t and "n" not in t:
        t += ".0"
    return t + "f"


def arr(name, rows):
    out = ["inline constexpr float %s[kGetUpBones * 7] = {" % name]
    for n, r in zip(names, rows):
        out.append("    " + ", ".join(fl(v) for v in r) + ",  // " + n)
    out.append("};")
    return "\n".join(out)


h = []
h.append("#pragma once")
h.append("// GENERATED by genframe0.py in this folder (not part of the build; rerun it to regenerate): frame 0 of the 1.2 set3 get-up")
h.append("// clips M_Neutral_GetUp_Back / _Front retargeted to the player rigs (Animations/retarget/out_sourcepack_{woman,man}_knee/*.utppclip.json,")
h.append("// 73-bone motion database order: local p.xyz, q.xyzw per bone = PoseRecord layout). The shipped motion databases do NOT carry these clips")
h.append("// (summary 'disabled'), so the R0 probe (GetUpProbe.hpp, MotionDriver.cpp) publishes this table instead of a database pose.")
h.append("// 2 bodies x 2 clips x 73 bones x 7 floats.")
h.append("// Sources: " + "; ".join(digests))
h.append("#include <cstdint>")
h.append("namespace utpp::ragdoll")
h.append("{")
h.append("inline constexpr uint32_t kGetUpBones = %d;" % len(names))
h.append("inline constexpr const char* kGetUpBoneNames[kGetUpBones] = {")
h.append("    " + ", ".join('"%s"' % n for n in names))
h.append("};")
for body in ("woman", "man"):
    for which in ("Back", "Front"):
        h.append(arr("kGetUp%s%sFrame0" % (body.capitalize(), which), tables[(body, which)]))
h.append("} // namespace utpp::ragdoll")
out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "GetUpFrame0.hpp")
open(out, "w", encoding="utf-8", newline="\n").write("\n".join(h) + "\n")
print("written", len(names), out)
