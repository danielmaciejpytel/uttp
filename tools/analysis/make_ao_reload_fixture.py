"""Builds plugin/UTPP/tests/data/recording_1215_aim_offset_reload.csv: the aim-offset input and the reload timing of every reload of the
recording 2026-10-21 12:15 that starts out of ADS or within 1 s of a shot (angles and flags only, no game data).

usage: python -I make_ao_reload_fixture.py <src.npz> <out.csv>
src.npz: the same per-pose-frame arrays as make_ao_replay_fixture.py (v, cam, hpm, act, aim, ovl, pitch).

Per reload edge (act becomes 2 with a weapon overlay: 1 Rifle, 3 Pistol2H) a window of 1.5 s before .. 1.6 s after it:
  raw_yaw = wrap(cam - hip line heading) (proxy of the visual root relative aim yaw), raw_pitch = camera pitch,
  ads = native ADS flag, shoot = weapon action 8, reload = weapon action 2.
The test replays the driver (UpperEnvelope, hipfire hold, AimHold) on these flags.
"""
import sys

import numpy as np


def wrap(a):
    return (a + 180.0) % 360.0 - 180.0


def main():
    z = np.load(sys.argv[1])
    v, act, aim, ovl = z['v'], z['act'], z['aim'], z['ovl']
    raw = wrap(z['cam'] - z['hpm'])
    pitch = z['pitch']
    n = len(v)
    last_shot = np.full(n, -1e9)
    lv = -1e9
    for i in range(n):
        if act[i] == 8:
            lv = v[i]
        last_shot[i] = lv
    edges = []
    for i in range(1, n):
        if act[i] == 2 and act[i - 1] != 2 and ovl[i] in (1, 3) and 0.0 <= v[i] <= 481.5:
            if aim[i - 1] == 1 or v[i] - last_shot[i] <= 1.0:
                edges.append(i)
    rows = []
    for si, e in enumerate(edges):
        idx = np.flatnonzero((v >= v[e] - 1.5) & (v <= v[e] + 1.6))
        for k, i in enumerate(idx):
            dt = 0.0 if k == 0 else v[i] - v[idx[k - 1]]
            rows.append('%d,%.4f,%.5f,%.4f,%.4f,%d,%d,%d,%d' % (si, v[i], dt, raw[i], pitch[i], 1 if aim[i] == 1 else 0,
                                                                  1 if act[i] == 8 else 0, 1 if act[i] == 2 else 0, int(ovl[i])))
    with open(sys.argv[2], 'w', newline='') as f:
        f.write('# UTPP AO reload episodes, rec 2026-10-21 12:15 (angles and flags only). Generated by tools/analysis/make_ao_reload_fixture.py\n')
        f.write('# one segment per reload edge (ADS or <= 1 s after a shot), 1.5 s before .. 1.6 s after; see the script\n')
        f.write('seg,video_s,dt,raw_yaw_deg,raw_pitch_deg,ads,shoot,reload,overlay\n')
        f.write('\n'.join(rows) + '\n')
    print('episodes', len(edges), 'rows', len(rows))
    for si, e in enumerate(edges):
        print('seg %d t0 %.3f overlay %d %s pitch %.1f' % (si, v[e], ovl[e], 'ADS' if aim[e - 1] == 1 else 'hipfire', pitch[e]))


if __name__ == '__main__':
    main()
