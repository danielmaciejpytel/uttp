"""Generates plugin/UTPP/tests/data/recording_1215_shot_turn.inc for tests/StationaryShotTurnTest.cpp (P5 FIX C, recording 2026-10-21 12:15).

The window is the recorded rifle hipfire shot followed by a fast camera turn (video 372.8-374.2 s): per pose frame the Shoot
action, the camera yaw shown (feed camDeg) and the visible body yaw (capsule yaw + Hips yaw of the final pose minus the game pose).

Usage: python -I gen_shot_turn_fixture.py <rec1215 dir with pose.npz, clockmap.py, common.py> <out .inc>
"""
import sys

HERE = sys.argv[1].replace('\\', '/').rstrip('/') + '/'
OUT = sys.argv[2]
import os
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..', '..', 'Tools', 'pylibs'))
sys.path.insert(0, HERE)
import numpy as np
from common import feed_arrays, ci, wrap

Z = np.load(HERE + 'pose.npz', allow_pickle=True)
meta = Z['meta']
d = Z['d']
t = meta[:, 0]
act = meta[:, 3].astype(int)
cols, F = feed_arrays()
ft = F['t']
yaw = ci(t, ft, F['yawDeg'])
cam = ci(t, ft, F['camDeg'])


def qyaw(q):
    x, y, z, w = q[..., 0], q[..., 1], q[..., 2], q[..., 3]
    fx = 2 * (x * y - w * z)
    fy = 1 - 2 * (x * x + z * z)
    return np.degrees(np.arctan2(-fx, fy))


off = wrap(qyaw(d[:, 2, 1, 3:7].astype(np.float64)) - qyaw(d[:, 0, 1, 3:7].astype(np.float64)))
vis = wrap(yaw + off)
V0 = 91.560
i0 = int(np.searchsorted(t, 372.8 + V0))
i1 = int(np.searchsorted(t, 374.2 + V0))
with open(OUT, 'w', newline='\n') as f:
    f.write('// generated by tools/analysis/gen_shot_turn_fixture.py from the 2026-10-21 12:15 recording (video 372.8-374.2 s)\n')
    f.write('// ShotFrame = { dt s, Shoot action, camera yaw shown deg, visible body yaw deg }\n')
    f.write('static const ShotFrame kShotFrames[] = {\n')
    for k in range(i0 + 1, i1):
        f.write('    {%.5ff, %d, %.2ff, %.2ff},\n' % (t[k] - t[k - 1], act[k], cam[k], vis[k]))
    f.write('};\n')
print('frames', i1 - i0 - 1)
