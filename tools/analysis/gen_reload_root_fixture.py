"""Generates plugin/UTPP/tests/data/recording_1215_reload_root.inc for tests/ReloadRootHoldTest.cpp (P4, recording 2026-10-21 12:15).

The recording is analysed per pose frame (feed_t clock). For each window the file holds what the native source pack offset root saw:
dt, the capsule yaw delta (feed yawDeg), the authored (animation) yaw delta, ADS, moving ground, the reload upper weight
(1 - MM upper weight) and the MEASURED visible-body offset (Hips yaw of the final pose minus the game pose, deg).
The authored yaw delta is inverted from the measured offset on every frame that is not a reload frame (no release there, so
offset' = offset + anim - capsule); on reload frames it is 0 (Idle loop). The test replays the policy and compares.

Usage: python -I gen_reload_root_fixture.py <rec1215 dir with pose.npz, clockmap.py, common.py> <out .inc>
The recording analysis is not a repository asset; only the numbers are committed.
"""
import sys

HERE = sys.argv[1].replace('\\', '/').rstrip('/') + '/'
OUT = sys.argv[2]
import os
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..', '..', 'Tools', 'pylibs'))
sys.path.insert(0, HERE)
import numpy as np
from common import feed_arrays, ci, wrap

Z = np.load(HERE + 'pose.npz', allow_pickle=True)
meta = Z['meta']
d = Z['d']
t = meta[:, 0]
act = meta[:, 3].astype(int)
aim = meta[:, 4].astype(int)
up = meta[:, 6]
cols, F = feed_arrays()
ft = F['t']
yaw = ci(t, ft, F['yawDeg'])
vx = np.interp(t, ft, np.nan_to_num(F['vx']))
vy = np.interp(t, ft, np.nan_to_num(F['vy']))
sp = np.hypot(vx, vy)


def qyaw(q):
    x, y, z, w = q[..., 0], q[..., 1], q[..., 2], q[..., 3]
    fx = 2 * (x * y - w * z)
    fy = 1 - 2 * (x * x + z * z)
    return np.degrees(np.arctan2(-fx, fy))


hips = [qyaw(d[:, layer, 1, 3:7].astype(np.float64)) for layer in range(4)]
off = wrap(hips[2] - hips[0])  # s2 (final) - s0 (game): visible body relative to the capsule
V0 = 91.560  # feed_t = video_s + 91.560

# (name, video window start, end, kind). stationary = recorded P4 scenario, moving = control (reload while running, sp 3.3 m/s)
WINDOWS = [('v81.5-83.8', 81.5, 83.8, 0), ('v85.3-89.0', 85.3, 89.0, 0), ('v91.3-95.6', 91.3, 95.6, 0),
           ('v353.6-354.8 moving control', 353.6, 354.8, 1)]

rows = []
eps = []
for name, v0, v1, kind in WINDOWS:
    i0 = int(np.searchsorted(t, v0 + V0))
    i1 = int(np.searchsorted(t, v1 + V0))
    first = len(rows)
    edge = -1
    for k in range(i0 + 1, i1):
        dt = t[k] - t[k - 1]
        cap = float(wrap(yaw[k] - yaw[k - 1]))
        if act[k] == 2 and edge < 0:
            edge = len(rows) - first
        anim = 0.0 if (act[k] == 2 or kind == 1) else float(wrap(off[k] - off[k - 1])) + cap
        reload_w = float(np.clip(1.0 - up[k], 0.0, 1.0))
        rows.append((dt, cap, anim, reload_w, float(off[k]), int(aim[k] == 1), int(sp[k] > 0.3)))
    assert edge > 0, name
    eps.append((name, first, len(rows) - first, edge, float(off[i0]), kind))

with open(OUT, 'w', newline='\n') as f:
    f.write('// generated by tools/analysis/gen_reload_root_fixture.py from the 2026-10-21 12:15 recording (pose frame clock);\n')
    f.write('// RootFrame = { dt s, capsule yaw delta deg, authored yaw delta deg, reload upper weight, measured offset deg, ads, moving }\n')
    f.write('static const RootFrame kRootFrames[] = {\n')
    for r in rows:
        f.write('    {%.5ff, %.4ff, %.4ff, %.3ff, %.2ff, %d, %d},\n' % r)
    f.write('};\n')
    f.write('// RootEpisode = { name, first frame, frame count, first reload frame (relative), seed offset deg, 1 = moving control }\n')
    f.write('static const RootEpisode kRootEpisodes[] = {\n')
    for e in eps:
        f.write('    {"%s", %d, %d, %d, %.2ff, %d},\n' % e)
    f.write('};\n')
print('rows', len(rows), [(e[0], e[2], e[3]) for e in eps])
