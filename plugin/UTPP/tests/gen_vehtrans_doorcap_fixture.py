"""Writes tests/vehtrans_doorcap_fixture.inc for the hold cap group (E) of MMVehicleTransitionTest.cpp.

Inputs (read only):
  - the recorded log and slide_table.json: the 30 measured car-door rides of the
    2026-11-02 test (entity root in the vehicle frame from the 'vtpp' log lines, x right / y forward, metres; door angle against time
    from the door-data frames),
  - scripts/utpp_vehicle_door_timing.reds: the generated UTPPCarDoorArcOf (copied into the fixture; re-run this script when that
    file is regenerated, the test then judges the new arcs).
Usage: python gen_vehtrans_doorcap_fixture.py   (run from anywhere; paths are relative to this file).
"""
import json
import re
from pathlib import Path

here = Path(__file__).resolve().parent
proj = here.parents[3]  # project root
diag = proj / 'Research' / 'logs' / 'gametest' / 'car-door2-20261102-diag' / 'slide'
series = json.loads((diag / 'slide_series.json').read_text(encoding='utf-8'))
table = json.loads((diag / 'slide_table.json').read_text(encoding='utf-8'))
reds = (here.parent / 'scripts' / 'utpp_vehicle_door_timing.reds').read_text(encoding='utf-8')

arcs = []
for m in re.finditer(r'if Equals\(seatVar, n"([a-z0-9_]+)"\) \{\s*a\.valid = true; a\.hingeX = ([-0-9.]+); a\.hingeY = ([-0-9.]+); '
                     r'a\.length = ([-0-9.]+); a\.closedDirDeg = ([-0-9.]+); a\.openDeg = ([-0-9.]+); a\.openDelayS = ([-0-9.]+); '
                     r'a\.openDurS = ([-0-9.]+);', reds):
    arcs.append((m.group(1),) + tuple(float(m.group(i)) for i in range(2, 9)))
assert len(arcs) >= 10, 'arc table not found in utpp_vehicle_door_timing.reds'

CLS = {'utility': 'utility4', 'sport1': 'sport1'}


def fl(v):
    t = '%.5g' % v
    if '.' not in t and 'e' not in t:
        t += '.0'
    return t + 'f'


out = ['// GENERATED by tests/gen_vehtrans_doorcap_fixture.py - do not edit. Included by MMVehicleTransitionTest.cpp (group E).',
       '// Source: the recorded log (30 car-door rides, entity root in the vehicle frame) and car-door3 rides 109 / 129 / 131 / 116 and the generated',
       '// UTPPCarDoorArcOf of scripts/utpp_vehicle_door_timing.reds (arcs below are a copy of it).',
       'struct DoorArcFx { const char* seat; float hx, hy, length, closedDeg, openDeg, delay, dur; };',
       'const DoorArcFx kDoorArcs[] = {']
for a in arcs:
    out.append('    {"%s", %s, %s, %s, %s, %s, %s, %s},' % ((a[0],) + tuple(fl(v) for v in a[1:])))
out.append('};')
out.append('struct DoorRideFx { int ride; const char* vehicle; const char* seat; int n; const float* t; const float* xy; int nDeg; const float* deg; };')
decl = []
for r in table['rides']:
    rid = r['ride']
    s = series[str(rid)]
    cls = CLS.get(r['cls'], r['cls'])
    side = 'left' if r['door'][1] == 'l' else 'right'
    seat = '%s_vehicle_seat_front_%s' % (cls, side)
    pairs = [(t, p) for t, p in zip(s['samples_t'], s['samples']) if t <= 1.25]
    out.append('static const float kFxT%d[] = {%s};' % (rid, ', '.join(fl(t) for t, _ in pairs)))
    out.append('static const float kFxXY%d[] = {%s};' % (rid, ', '.join('%s, %s' % (fl(p[0]), fl(p[1])) for _, p in pairs)))
    deg = [s['door_deg'][i] for i in range(0, 101, 2)]  # 0.00 .. 1.00 s every 0.02 s
    out.append('static const float kFxDeg%d[] = {%s};' % (rid, ', '.join(fl(abs(d)) for d in deg)))
    decl.append('    {%d, "%s", "%s", %d, kFxT%d, kFxXY%d, %d, kFxDeg%d},' % (rid, r['vehicle'], seat, len(pairs), rid, rid, len(deg), rid))

# Rides 100 + N: the capped rides of the 2026-11-02 11:02-11:59 test (install UTPP-door3, the recorded log),
# read straight from the game log: the entity root = the CET utpp_vehiclecam 'vtpp' samples (vehicle frame, seconds after the BeginMount = ride-entry line
# time + |capArriveAt| of the 'vehtrans mount' line) plus the three native 'mountdiag' points (d metres along the slide direction anchor -> settled
# position at +9 / +27 / +41 ms). The door angle has no door-data frames in that run: each ride reuses the measured degree series of the door2 ride of
# the same vehicle and door (columbus 9, bratsk door 30, bratsk passenger 32, emperor passenger 16). The logged capState / start / tail / peak of each
# ride are written next to it ('LOGGED' comment) and checked by the test.
D3 = proj / 'Research' / 'logs' / 'gametest' / 'car-door3-20261102'
D3_RIDES = [  # (fixture ride, vehicle label, folder, log file, native ride counter, door2 ride whose door angle is reused)
    (109, 'columbus3', 'columbus', 'normal_cycle_door-lines.txt', 9, 9),
    (129, 'bratsk3', 'bratsk', 'normal_cycle_door-lines.txt', 29, 30),
    (131, 'bratsk3', 'bratsk', 'passenger-lines.txt', 31, 32),
    (116, 'emperor3', 'emperor', 'passenger-lines.txt', 16, 16),
]
_tre = re.compile(r'^\[2026-11-02 (\d+):(\d+):(\d+\.\d+)\]')


def _ts(line):
    m = _tre.match(line)
    return int(m.group(1)) * 3600 + int(m.group(2)) * 60 + float(m.group(3)) if m else None


for fid, label, folder, fname, nride, door2 in D3_RIDES:
    lines = (D3 / folder / fname).read_text(encoding='utf-8', errors='replace').splitlines()
    mi = [i for i, l in enumerate(lines) if ('vehtrans mount: ride=%d ' % nride) in l and 'capState=2' in l][0]
    md = [i for i in range(mi) if ('mountdiag: ride=%d ' % nride) in lines[i]][-1]
    ei = [i for i in range(md) if 'utpp_vehicle_door] ride-entry' in lines[i]][-1]
    mm = re.search(r'holdCap=([0-9.]+).*capArriveAt=(-?[0-9.]+) capStartAt=([0-9.]+) capTail=([0-9.]+)', lines[mi])
    peak = float(re.search(r'rootPeakDist=([0-9.]+)', lines[mi]).group(1))
    seat = re.search(r'seat=(\S+)', lines[ei]).group(1)
    t0 = _ts(lines[ei]) - float(mm.group(2))
    d_pts = [(float(a) / 1000.0, float(d)) for a, d in re.findall(r's\d=\+(\d+)ms veh=\d d=([0-9.]+)m', lines[md])]
    vt = []
    for l in lines[ei - 3:mi + 40]:
        m = re.search(r'\[utpp_vehiclecam\] t=[0-9.]+ cam .* vtpp=\(([-0-9.]+),([-0-9.]+),([-0-9.]+)\)', l)
        if m:
            vt.append((_ts(l) - t0, float(m.group(1)), float(m.group(2))))
    vt = [v for v in vt if v[0] <= 1.25]
    am = re.search(r'anchor=\(([-0-9.]+),([-0-9.]+)\)', lines[ei])  # the pre-mount position the door script capped for
    a0 = (float(am.group(1)), float(am.group(2)))
    vt[0] = (vt[0][0], a0[0], a0[1])
    settled = [v for v in vt if v[0] >= 0.3][0][1:]
    dd = ((settled[0] - a0[0]) ** 2 + (settled[1] - a0[1]) ** 2) ** 0.5
    u = ((settled[0] - a0[0]) / dd, (settled[1] - a0[1]) / dd)
    pts = [(vt[0][0], a0)] + [(t, (a0[0] + d * u[0], a0[1] + d * u[1])) for t, d in d_pts] + [(t, (x, y)) for t, x, y in vt[1:] if t > d_pts[-1][0] + 0.01]
    out.append('// ride %d: %s %s door3 ride %d; LOGGED holdCap=%s capArriveAt=%s capStartAt=%s capTail=%s rootPeakDist=%.2f; door angle of door2 ride %d'
               % (fid, label, seat, nride, mm.group(1), mm.group(2), mm.group(3), mm.group(4), peak, door2))
    out.append('static const float kFxT%d[] = {%s};' % (fid, ', '.join(fl(t) for t, _ in pts)))
    out.append('static const float kFxXY%d[] = {%s};' % (fid, ', '.join('%s, %s' % (fl(p[0]), fl(p[1])) for _, p in pts)))
    out.append('static const float kFxDeg%d[] = {%s};' % (fid, ', '.join(fl(abs(series[str(door2)]['door_deg'][i])) for i in range(0, 101, 2))))
    decl.append('    {%d, "%s", "%s", %d, kFxT%d, kFxXY%d, 51, kFxDeg%d},' % (fid, label, seat, len(pts), fid, fid, fid))
out.append('const DoorRideFx kDoorRides[] = {')
out.extend(decl)
out.append('};')
(here / 'vehtrans_doorcap_fixture.inc').write_text('\n'.join(out) + '\n', encoding='utf-8')
print('wrote', len(arcs), 'arcs,', len(decl), 'rides')
