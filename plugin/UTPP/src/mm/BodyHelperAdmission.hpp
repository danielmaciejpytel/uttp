inline constexpr int32_t kBodyWoman = 0, kBodyMan = 1, kBodyNone = -1;

// What a bundle needs from the merged player rig. The rig varies with character customisation (the woman rig seen in 8 sessions
// is the 619-bone base plus 26 hair-chain bones under Head; the man rig is the bare base, 619 bones), so the whole rig is NOT
// fingerprinted. Instead a signature covers only the bones the bundle's plan reads and writes (binding.dat: CORE, OWNED, CHILD,
// ANCHOR) plus all of their ancestors, as (name hash, parent name hash) pairs sorted by name hash, FNV-1a 64 (each hash as 8
// little-endian bytes, root parent = 0). Bone indices, bone order and every other bone are irrelevant. The same value is computed
// offline by tools/analysis/helper_rig_signature.py. Direct non-owned children of owned bones are not part of it: the plan
// builder (helperpatch::Prepare) refuses a rig that has any child of an owned bone outside the bundle's compensation catalog.
struct RigSignature
{
    bool ok = false;           // false: malformed rig (duplicate name, parent out of range) or a bundle bone is absent
    uint32_t bones = 0;        // closure size
    uint64_t fingerprint = 0;
};

template <class Parent>
inline RigSignature ComputeRigSignature(std::span<const uint64_t> names, std::span<const Parent> parents, std::span<const uint64_t> roots)
{
    RigSignature out;
    const size_t n = names.size();
    if (n == 0 || n != parents.size() || n > 0x7fffffffu) return out;
    std::vector<std::pair<uint64_t, int32_t>> byName(n);
    for (size_t i = 0; i < n; ++i) byName[i] = {names[i], static_cast<int32_t>(i)};
    std::sort(byName.begin(), byName.end());
    for (size_t i = 1; i < n; ++i)
        if (byName[i].first == byName[i - 1].first) return out;
    auto find = [&](uint64_t name) -> int32_t {
        const auto it = std::lower_bound(byName.begin(), byName.end(), std::pair<uint64_t, int32_t>{name, INT32_MIN});
        return it != byName.end() && it->first == name ? it->second : -1;
    };
    std::vector<uint8_t> marked(n, 0);
    for (const uint64_t root : roots)
    {
        int32_t i = find(root);
        if (i < 0) return out;
        while (i >= 0 && !marked[static_cast<size_t>(i)])
        {
            marked[static_cast<size_t>(i)] = 1;
            const int32_t p = static_cast<int32_t>(parents[static_cast<size_t>(i)]);
            if (p < -1 || p >= static_cast<int32_t>(n)) return out;
            i = p;
        }
    }
    std::vector<std::pair<uint64_t, uint64_t>> pairs;
    for (size_t i = 0; i < n; ++i)
        if (marked[i])
        {
            const int32_t p = static_cast<int32_t>(parents[i]);
            pairs.push_back({names[i], p >= 0 ? names[static_cast<size_t>(p)] : 0});
        }
    std::sort(pairs.begin(), pairs.end());
    uint64_t h = 0xcbf29ce484222325ull;
    auto feed = [&h](uint64_t value) {
        for (uint32_t b = 0; b < 8; ++b) { h ^= (value >> (8 * b)) & 0xffu; h *= 0x100000001b3ull; }
    };
    for (const auto& pr : pairs) { feed(pr.first); feed(pr.second); }
    out.ok = true; out.bones = static_cast<uint32_t>(pairs.size()); out.fingerprint = h;
    return out;
}

struct Approved
{
    int32_t body;
    std::string_view programSha256, bindingSha256; // lower-case hex of the exact file bytes
    uint32_t owned, children;
    uint32_t baseMinBones;        // the merged rig must have at least this many bones (0 = accepts no rig)
    uint32_t closureBones;        // size of the bundle's closure in the rig (RigSignature::bones)
    uint64_t closureFingerprint;  // RigSignature::fingerprint (0 = accepts no rig)
};

