"""Builds plugin/UTPP/tests/data/recording_1215_aim_offset_replay.csv: the aim-offset spine-yaw INPUT (angles only, no game data) of the
recording 2026-10-21 12:15 around every one-frame spine jump.

usage: python -I make_ao_replay_fixture.py <src.npz> <out.csv>
src.npz (per pose-CSV frame, 33916 frames; made from the rec1215 analysis of utpp-pose-1677076533654.csv + the camTrace of the
game log): v = video seconds, cam = camera yaw (deg), hpm = hip line heading of the mm layer (deg), shm = shoulder line
heading (deg), act = weapon action (2 reload, 8 shoot), aim = native ADS flag, ovl = overlay (1 Rifle, 3 Pistol2H),
pitch = camera pitch (deg).

Proxy of the MotionPose aim offset input (the visual root yaw is not logged, the hip line replaces it, error ~10 deg):
  raw_yaw   = wrap(cam - hpm)                       (ComputeAim: camera yaw relative to the visual root, + = left)
  have_aim  = shoot | native ADS | 0..0.75 s after the last shoot (HipFirePoseHold) except during reload
              | 0.30 s after a reload start that interrupted ADS (ReloadUpperEnvelope AimHold)
Windows: 2.0 s before .. 1.5 s after each frame whose shoulder-hip twist changed by >= 40 deg in one frame (the 30 jumps), the
fast-flick windows 109.0-110.0 s and 111.0-112.0 s, plus
three calm 4 s windows of continuous ADS without such a jump and with a camera slower than 400 deg/s. Rows: seg, video_s, dt (0 on the first row of a segment),
raw_yaw_deg, raw_pitch_deg, have_aim, overlay.
"""
import sys

import numpy as np


def wrap(a):
    return (a + 180.0) % 360.0 - 180.0


def main():
    z = np.load(sys.argv[1])
    v, act, aim = z['v'], z['act'], z['aim']
    cam, hpm, shm = z['cam'], z['hpm'], z['shm']
    ovl, pitch = z['ovl'], z['pitch']
    n = len(v)
    raw = wrap(cam - hpm)
    tw = wrap(shm - hpm)
    dtw = np.r_[0.0, wrap(np.diff(tw))]
    inv = (v >= 0) & (v <= 481.5)
    last_shot = np.full(n, -1e9)
    lv = -1e9
    for i in range(n):
        if act[i] == 8:
            lv = v[i]
        last_shot[i] = lv
    since = v - last_shot
    have = (act == 8) | (aim == 1) | ((since >= 0) & (since <= 0.75) & (act != 2))
    hold_until = -1e9
    for i in range(1, n):
        if act[i] == 2 and act[i - 1] != 2 and aim[i - 1] == 1:
            hold_until = v[i] + 0.30
        if act[i] == 2 and v[i] <= hold_until:
            have[i] = True
    events = np.flatnonzero(inv & (np.abs(dtw) >= 40.0))
    wins = []
    for i in events:
        wins.append([v[i] - 2.0, v[i] + 1.5])
    # fast camera flicks on the same side (1000-1300 deg/s inside the +-60 clamp, hipfire shots): the filter must track them exactly
    wins += [[109.0, 110.0], [111.0, 112.0]]
    # calm ADS windows
    near_event = np.zeros(n, bool)
    for i in events:
        near_event |= (v > v[i] - 6.0) & (v < v[i] + 6.0)
    calm = []
    i = 0
    while i < n and len(calm) < 3:
        if inv[i] and aim[i] == 1 and not near_event[i] and ovl[i] != 0:
            j = i
            while j < n and aim[j] == 1 and not near_event[j] and ovl[j] != 0 and v[j] - v[i] < 4.0:
                j += 1
            if v[j - 1] - v[i] >= 3.9:
                rate = np.abs(wrap(np.diff(raw[i:j]))) / np.maximum(np.diff(v[i:j]), 1e-4)
                if rate.max() < 400.0:  # slower than the 480 deg/s rate limit of the filter: the unchanged calm case
                    calm.append([v[i], v[j - 1]])
                i = j
                continue
        i += 1
    wins += calm
    wins.sort()
    merged = []
    for w in wins:
        if merged and w[0] <= merged[-1][1]:
            merged[-1][1] = max(merged[-1][1], w[1])
        else:
            merged.append(list(w))
    rows = []
    for si, (a, b) in enumerate(merged):
        idx = np.flatnonzero((v >= a) & (v <= b))
        for k, i in enumerate(idx):
            dt = 0.0 if k == 0 else v[i] - v[idx[k - 1]]
            rows.append('%d,%.4f,%.5f,%.4f,%.4f,%d,%d' % (si, v[i], dt, raw[i], pitch[i], 1 if have[i] else 0, int(ovl[i])))
    with open(sys.argv[2], 'w', newline='') as f:
        f.write('# UTPP AO spine-yaw input replay, rec 2026-10-21 12:15 (angles only). Generated by tools/analysis/make_ao_replay_fixture.py\n')
        f.write('# proxy: raw_yaw = wrap(cam - hip line heading), have_aim = shoot|ADS|0.75 s hipfire hold|0.3 s reload aim hold; see the script\n')
        f.write('seg,video_s,dt,raw_yaw_deg,raw_pitch_deg,have_aim,overlay\n')
        f.write('\n'.join(rows) + '\n')
    print('events', len(events), 'windows', len(merged), '(calm %d)' % len(calm), 'rows', len(rows))


if __name__ == '__main__':
    main()
