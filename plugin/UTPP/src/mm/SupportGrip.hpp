// Bounds of the stock pass (m along the barrel): the weapon is never moved by more than this; a larger request is not a stock gap.
inline constexpr float kMaxStockPull = 0.12f, kMaxStockPush = 0.03f;
// Support-grip gate: time (s) for 0 <-> 1 when the route appears / disappears (holster, hand-back): no one-frame hand jump.
inline constexpr float kGateSeconds = 0.2f;
// Hand speed bound of the gate: the gate (release / regrip) and the reach shift run over
// GateSeconds(travel) = max(0.2 s, travel / 0.6 m/s), travel = the left hand's way between its own (overlay / game) pose and the game's
// grip of the weapon + the weapon's reach-shift cap; 0.6 m/s = 2.0 cm per 30 Hz frame, 0.5 cm under the 2.5 cm continuity bound for the other
// motion of the frame (Hercules ~25 + 10 cm -> 0.58 s).
inline constexpr float kMaxHandSpeed = 0.6f;
inline float GateSeconds(float aTravelM)
{
    return std::isfinite(aTravelM) ? std::fmax(kGateSeconds, aTravelM / kMaxHandSpeed) : kGateSeconds;
}
// Way (m) of the left hand to the game's grip of aE on the pose as it is (before the grip IK) + the weapon's reach-shift cap.
inline float GateTravel(const ov::Skeleton& aSk, const ov::Pose& aPose, const gik::Rig& aRig, const Entry& aE)
{
    if (!aRig.Valid(aSk))
        return 0.0f;
    Quat rw, rh;
    Vec3 pw, ph;
    gik::ModelOf(aSk, aPose, aRig.weaponRight, rw, pw);
    gik::ModelOf(aSk, aPose, aRig.left.hand, rh, ph);
    return gik::Len(pw + math::QuatRotate(rw, aE.t) - ph) + aE.maxShift;
}

// Rate-limited gate of the route (the left hand and the weapon follow the weight, never a switch).
struct Gate
{
    float g = 0.0f;
    const Entry* last = nullptr;
    bool have = false; // false after Reset: the first frame takes its target at once (a fresh start shows the pose, no ramp)
    void Reset()
    {
        g = 0.0f;
        last = nullptr;
        have = false;
    }
    // aWant with an entry: rise toward 1; else fall toward 0 with the last entry seen. A different weapon under a raised gate first falls
    // to 0 with the old entry (no jump between two grips), then rises with the new one. dt 0 (same frame again) keeps the gate.
    // Returns the entry to apply this frame (nullptr = gate closed).
    const Entry* Step(const Entry* aEntry, bool aWant, float aDt, float aSeconds = kGateSeconds)
    {
        const bool want = aWant && aEntry;
        if (!have)
        {
            have = true;
            last = aEntry;
            g = want ? 1.0f : 0.0f;
            return g > 0.0f ? last : nullptr;
        }
        const float sec = std::isfinite(aSeconds) ? std::fmax(kGateSeconds, aSeconds) : kGateSeconds;
        const float step = std::isfinite(aDt) && aDt > 0.0f ? std::fmin(aDt, 0.1f) / sec : 0.0f;
        if (aEntry && aEntry != last)
        {
            if (last && g > 0.0f)
            {
                g = std::fmax(0.0f, g - step);
                return g > 0.0f ? last : nullptr;
            }
            last = aEntry;
        }
        g = want ? std::fmin(1.0f, g + step) : std::fmax(0.0f, g - step);
        return g > 0.0f ? last : nullptr;
    }
};

// Grip target: the authored (overlay) relative grip blended toward the game's grip of the weapon by aW.
inline gik::Grip BlendGrip(const gik::Grip& aAuthored, const Entry& aE, float aW)
{
    const float w = ov::Clamp01(aW);
    gik::Grip g = aAuthored;
    if (!(w > ov::kZeroWeight))
        return g;
    if (!aAuthored.valid)
    {
        g.t = aE.t;
        g.r = aE.r;
        g.valid = true;
        return g;
    }
    g.t = math::Lerp(aAuthored.t, aE.t, w);
    g.r = ov::Nlerp(aAuthored.r, aE.r, w);
    g.valid = math::IsFinite(g.t) && math::IsFinite(g.r);
    return g;
}

// Largest weight in [0, aW] whose blended grip target lies within aSoftStart x the left arm length of the left shoulder (LeftArm) on
// the current pose. aW itself when it fits; 0 when even the authored grip does not fit (then the pose keeps its old behaviour).
// Bisection, 10 steps (0.1 % of the weight), positions only.
inline float ReachLimitedWeight(const ov::Skeleton& aSk, const ov::Pose& aPose, const gik::Rig& aRig, const gik::Grip& aAuthored,
                                const Entry& aE, float aW, float aSoftStart)
{
    const float w = ov::Clamp01(aW);
    if (!(w > ov::kZeroWeight) || !aRig.Valid(aSk))
        return 0.0f;
    Quat rw, rs;
    Vec3 pw, ps;
    gik::ModelOf(aSk, aPose, aRig.weaponRight, rw, pw);
    gik::ModelOf(aSk, aPose, aRig.left.upper, rs, ps);
    const float full = gik::Len(aPose.b[aRig.left.lower].t) + gik::Len(aPose.b[aRig.left.hand].t);
    const float safe = full * aSoftStart;
    const auto fits = [&](float x) {
        const gik::Grip g = BlendGrip(aAuthored, aE, x);
        return gik::Len(pw + math::QuatRotate(rw, g.t) - ps) <= safe;
    };
    if (fits(w))
        return w;
    if (!fits(0.0f))
        return 0.0f;
    float lo = 0.0f, hi = w;
    for (int k = 0; k < 10; ++k)
    {
        const float mid = 0.5f * (lo + hi);
        (fits(mid) ? lo : hi) = mid;
    }
    return lo;
}

// Wrist bend (deg): angle between the hand bone axis and the forearm bone axis for a hand local rotation (both bone axes local +x in
// the CP rig, rest bend 0). The support-grip weight below keeps it at or under kSupportWristBendLimitDeg.
inline constexpr float kSupportWristBendLimitDeg = 75.0f;
inline float WristBendDeg(const Quat& aHandLocal)
{
    const Vec3 x = math::QuatRotate(math::QuatNormalize(aHandLocal), Vec3{1.0f, 0.0f, 0.0f});
    return std::acos(std::fmax(-1.0f, std::fmin(1.0f, x.x))) * (180.0f / math::kPi);
}

// Largest weight in [0, aW] whose blended grip keeps the support-hand twist at or under the limit once the left arm reaches it: per
// candidate the left arm is solved to the target on a scratch copy (two-bone IK, game forearm convention, then the swivel limit of
// ForearmTwist.hpp at full weight) and the remaining |twist| is read. Allowed = max(aLimitDeg, |twist at weight 0|): a pose that is
// already over the limit without the route is never pushed further, and the route never raises it past the limit (Defender: the game
// grip asks 104-119 deg at the overlay's elbow bend, beyond the 60 deg swivel). aW itself when it fits; bisection, 10 steps.
// The same candidate solve also keeps the wrist bend (WristBendDeg) at or under max(aBendLimitDeg, bend at weight 0): the shoulder-aim
// grip of the SMGs bends the support wrist 97-115 deg on the low carry elbow of the Relaxed poses (a curled fist at the belly), while
// Ready / Aiming stay at 25-59 deg and keep the full grip.
inline float TwistLimitedWeight(const ov::Skeleton& aSk, const ov::Pose& aPose, const gik::Rig& aRig, const ov::ForearmTwistRig& aTwistRig,
                                const gik::Grip& aAuthored, const Entry& aE, float aW, const gik::Params& aP, float aLimitDeg,
                                float aMaxSwivelDeg, float aBendLimitDeg = kSupportWristBendLimitDeg, float* aTwistOnlyW = nullptr)
{
    if (aTwistOnlyW)
        *aTwistOnlyW = 0.0f;
    const float w = ov::Clamp01(aW);
    if (!(w > ov::kZeroWeight) || !aRig.Valid(aSk))
        return 0.0f;
    Quat rw;
    Vec3 pw;
    gik::ModelOf(aSk, aPose, aRig.weaponRight, rw, pw);
    static thread_local ov::Pose scratch;
    scratch = aPose;
    const int bones[3] = {aRig.left.upper, aRig.left.lower, aRig.left.hand};
    float bend = 0.0f; // wrist bend of the last candidate solve
    const auto twistAt = [&](float x) {
        for (const int b : bones)
            scratch.b[b] = aPose.b[b];
        const gik::Grip g = BlendGrip(aAuthored, aE, x);
        const Vec3 tp = pw + math::QuatRotate(rw, g.t);
        const Quat tr = math::QuatNormalize(math::QuatMul(rw, g.r));
        gik::Result r;
        gik::SolveArm(aSk, scratch, aRig.left, tp, &tr, 1.0f, aP, r);
        float moved[2] = {};
        ov::MoveForearmTwistToHands(aTwistRig, scratch, moved);
        const ov::HandTwistLimitResult lim = ov::LimitHandTwistBySwivel(scratch, aRig.left.upper, aRig.left.lower, aRig.left.hand,
                                                                         aTwistRig.childCount[0], aLimitDeg, aMaxSwivelDeg, 1.0f);
        bend = WristBendDeg(scratch.b[aRig.left.hand].r);
        return std::fabs(lim.twistAfterDeg);
    };
    const float allowed = std::fmax(aLimitDeg, twistAt(0.0f)) + 0.01f;
#if defined(UTPP_SUPPORTGRIP_MUTATION) && UTPP_SUPPORTGRIP_MUTATION == 2
    const float allowedBend = std::numeric_limits<float>::infinity(); // mutation 2: no wrist-bend term (the build before)
#else
    const float allowedBend = std::fmax(aBendLimitDeg, bend) + 0.01f;
#endif
    const auto fits = [&](float x) { return twistAt(x) <= allowed && bend <= allowedBend; };
    const bool twistFitsW = twistAt(w) <= allowed;
    if (twistFitsW && bend <= allowedBend)
    {
        if (aTwistOnlyW)
            *aTwistOnlyW = w;
        return w;
    }
    // aTwistOnlyW: the same weight without the wrist-bend term (the twist limit alone)
    if (aTwistOnlyW)
    {
        if (twistFitsW)
            *aTwistOnlyW = w;
        else
        {
            float tlo = 0.0f, thi = w;
            for (int k = 0; k < 10; ++k)
            {
                const float mid = 0.5f * (tlo + thi);
                (twistAt(mid) <= allowed ? tlo : thi) = mid;
            }
            *aTwistOnlyW = tlo;
        }
    }
    float lo = 0.0f, hi = w;
    for (int k = 0; k < 10; ++k)
    {
        const float mid = 0.5f * (lo + hi);
        (fits(mid) ? lo : hi) = mid;
    }
    return lo;
}

// Reach shift: when the left arm cannot reach the handguard, the weapon slides along its own barrel
// toward the body just enough that the grip target (aW-blended) lies inside aSoftStart x the left arm length; capped per weapon at
// Entry::maxShift (kMaxReachShift; Hercules 10 cm, it needs 8.4 F / 9.2 M) and rate-limited in MotionPose like the
// gate (the cap in GateSeconds). Returns the needed slide (m, >= 0, NOT capped: diagnostics report what a weapon would need).
inline constexpr float kMaxReachShift = 0.03f;
inline float ReachShiftNeeded(const ov::Skeleton& aSk, const ov::Pose& aPose, const gik::Rig& aRig, const gik::Grip& aAuthored, const Entry& aE,
                              float aW, float aSoftStart)
{
    const float w = ov::Clamp01(aW);
    if (!(w > ov::kZeroWeight) || !aRig.Valid(aSk))
        return 0.0f;
    Quat rw, rs;
    Vec3 pw, ps;
    gik::ModelOf(aSk, aPose, aRig.weaponRight, rw, pw);
    gik::ModelOf(aSk, aPose, aRig.left.upper, rs, ps);
    const float safe = (gik::Len(aPose.b[aRig.left.lower].t) + gik::Len(aPose.b[aRig.left.hand].t)) * aSoftStart;
    const gik::Grip g = BlendGrip(aAuthored, aE, w);
    const Vec3 d = pw + math::QuatRotate(rw, g.t) - ps;
    const Vec3 a = math::QuatRotate(rw, Vec3{0.0f, 1.0f, 0.0f});
    const float dd = math::Dot(d, d), da = math::Dot(d, a);
    if (!std::isfinite(dd) || !std::isfinite(da) || dd <= safe * safe)
        return 0.0f;
    const float disc = da * da - dd + safe * safe;
    const float s = disc >= 0.0f ? da - std::sqrt(disc) : da; // no slide reaches: the one closest to the shoulder
    return std::fmax(0.0f, s);
}
// Slides the weapon by -aSlide along its barrel (toward the body; < 0 = away from it, the unwinding of a stock pass that had pushed the
// weapon forward) by moving RightHand with the right-arm IK (hand rotation kept).
inline bool SlideWeaponBack(const ov::Skeleton& aSk, ov::Pose& aIo, const gik::Rig& aRig, float aSlide, const gik::Params& aP)
{
    if (!(std::fabs(aSlide) > 1e-5f) || !aRig.Valid(aSk))
        return false;
    Quat rw, rh;
    Vec3 pw, ph;
    gik::ModelOf(aSk, aIo, aRig.weaponRight, rw, pw);
    gik::ModelOf(aSk, aIo, aRig.right.hand, rh, ph);
    const Vec3 a = math::QuatRotate(rw, Vec3{0.0f, 1.0f, 0.0f});
    const ov::Xf keep[3] = {aIo.b[aRig.right.upper], aIo.b[aRig.right.lower], aIo.b[aRig.right.hand]};
    gik::Result r;
    if (!gik::SolveArm(aSk, aIo, aRig.right, ph - a * aSlide, &rh, 1.0f, aP, r) || !r.ok || r.handErr > 0.002f)
    {
        aIo.b[aRig.right.upper] = keep[0];
        aIo.b[aRig.right.lower] = keep[1];
        aIo.b[aRig.right.hand] = keep[2];
        return false;
    }
    return true;
}

using FingerBones = std::array<int, kFingerCount>;
template <class NameFn>
inline FingerBones FindFingers(int aCount, NameFn aName)
{
    FingerBones out{};
    for (int k = 0; k < kFingerCount; ++k)
    {
        out[k] = -1;
        for (int i = 0; i < aCount; ++i)
            if (aName(i) == std::string_view(kFingerBones[k]))
            {
                out[k] = i;
                break;
            }
    }
    return out;
}

// Release of the route (review round 5, 2026-11-10). While the gate falls with an entry that is not this frame's weapon data (another
// weapon, an overlay switch, a lost record: in.supportGrip != Gate::last), none of the old weapon's grip, stock or reach geometry is
// applied to the pose (it may hold another weapon). Two things keep it continuous instead:
//  - the weapon's slide of the last frame the route ran with its own data (reach shift + stock pass, along the barrel) falls with one
//    fraction f (route weight now / then, never rising), so the weapon and the right hand never jump;
//  - the left hand follows its target of each frame (the pose and grip IK as they are now) with an offset that starts at the gap to
//    where the hand was last frame and shrinks by at most kMaxHandSpeed per second (rotation, finger locals: kMaxHandTurn), so the hand
//    leaves the handguard from where it is; full IK weight (a partial weight blends joint rotations: the hand would swing in an arc).
// The follower anchors only when the route drops while its gate is open (release, no Rifle pose weight left), and re-anchors on a
// switch of the hand's target source while it is still moving; otherwise the pose is untouched bit for bit.
inline constexpr float kHandRadiusM = 0.1f;                         // hand + fingers lever about the wrist (m)
inline constexpr float kMaxHandTurn = kMaxHandSpeed / kHandRadiusM; // 6 rad/s: 0.6 m/s at the finger tips
struct Release
{
    // slides of the last frame the route ran with its own data (m along the barrel, + = weapon toward the body)
    float routeW = 0.0f, reach = 0.0f, stock = 0.0f, f = 1.0f;
    bool slideValid = false;
    // left-hand follower: last output (Spine3 frame, finger locals), offsets (target -> output)
    bool prevValid = false, prevApplied = false, prevSource = false, active = false;
    Vec3 prevT{}, o{};
    Quat prevR{}, qo{};
    std::array<Quat, kFingerCount> prevF{}, fo{};
    void ResetSlides()
    {
        routeW = reach = stock = 0.0f;
        f = 1.0f;
        slideValid = false;
    }
    void Reset() { *this = Release{}; }
};
namespace detail
{
// rotation offset aQ shrunk by aStep radians toward identity; aLeft = angle left
inline Quat ShrinkTurn(const Quat& aQ, float aStep, float& aLeft)
{
    const Vec3 v = math::QuatToScaledAngleAxis(math::QuatAbs(aQ));
    const float a = gik::Len(v);
    aLeft = std::fmax(0.0f, a - aStep);
    return a > 1e-7f && aLeft > 0.0f ? math::QuatFromScaledAngleAxis(v * (aLeft / a)) : Quat{};
}
} // namespace detail
// One frame of the left-hand follower, after the grip IK. aApplied: the route's grip acts on the left hand this frame; aDrop: the route
// dropped this frame with its gate still open; aSource: the hand's target comes from the authored grip; aSlide: a release slide is
// fading this frame. Returns the position offset left (m).
inline float FollowLeftHand(const ov::Skeleton& aSk, ov::Pose& aIo, const gik::Rig& aRig, int aSpine3, const FingerBones& aFingers,
                            bool aApplied, bool aDrop, bool aSource, bool aSlide, float aDt, const gik::Params& aP, Release& aR)
{
    if (aSpine3 < 0 || aSpine3 >= aSk.n || !aRig.Valid(aSk))
    {
        aR.prevValid = aR.active = false;
        return 0.0f;
    }
    Quat rs, rh;
    Vec3 ps, ph;
    gik::ModelOf(aSk, aIo, aSpine3, rs, ps);
    gik::ModelOf(aSk, aIo, aRig.left.hand, rh, ph);
    const Quat irs = math::QuatInv(rs);
    const Vec3 tT = math::QuatRotate(irs, ph - ps);
    const Quat tR = math::QuatNormalize(math::QuatMul(irs, rh));
    const bool toggled = aApplied != aR.prevApplied || aSource != aR.prevSource;
    if (aR.prevValid && (aDrop || ((aR.active || aSlide) && toggled)))
    {
        aR.o = aR.prevT - tT;
        aR.qo = math::QuatNormalize(math::QuatMul(math::QuatInv(tR), aR.prevR));
        for (int k = 0; k < kFingerCount; ++k)
        {
            const int b = aFingers[static_cast<size_t>(k)];
            aR.fo[static_cast<size_t>(k)] = b >= 0 && b < aIo.n
                ? math::QuatNormalize(math::QuatMul(math::QuatInv(aIo.b[b].r), aR.prevF[static_cast<size_t>(k)])) : Quat{};
        }
        aR.active = true;
    }
    aR.prevApplied = aApplied;
    aR.prevSource = aSource;
    float left = 0.0f;
    if (aR.active)
    {
        const float dt = std::isfinite(aDt) && aDt > 0.0f ? std::fmin(aDt, 0.1f) : 0.0f;
        const float len = gik::Len(aR.o);
        left = std::fmax(0.0f, len - kMaxHandSpeed * dt);
        aR.o = len > 1e-7f ? aR.o * (left / len) : Vec3{};
        float turn = 0.0f, fingerTurn = 0.0f;
        aR.qo = detail::ShrinkTurn(aR.qo, kMaxHandTurn * dt, turn);
        for (int k = 0; k < kFingerCount; ++k)
        {
            float l = 0.0f;
            aR.fo[static_cast<size_t>(k)] = detail::ShrinkTurn(aR.fo[static_cast<size_t>(k)], kMaxHandTurn * dt, l);
            fingerTurn = std::fmax(fingerTurn, l);
        }
        const Vec3 hp = ps + math::QuatRotate(rs, tT + aR.o);
        const Quat hr = math::QuatNormalize(math::QuatMul(rs, math::QuatMul(tR, aR.qo)));
        gik::Result r;
        if (left > 0.0f || turn > 0.0f)
            gik::SolveArm(aSk, aIo, aRig.left, hp, &hr, 1.0f, aP, r);
        for (int k = 0; k < kFingerCount; ++k)
        {
            const int b = aFingers[static_cast<size_t>(k)];
            if (b >= 0 && b < aIo.n)
                aIo.b[b].r = math::QuatNormalize(math::QuatMul(aIo.b[b].r, aR.fo[static_cast<size_t>(k)]));
        }
        aR.active = left > 0.0f || turn > 0.0f || fingerTurn > 0.0f;
    }
    // this frame's output for the next one
    gik::ModelOf(aSk, aIo, aRig.left.hand, rh, ph);
    aR.prevT = math::QuatRotate(irs, ph - ps);
    aR.prevR = math::QuatNormalize(math::QuatMul(irs, rh));
    for (int k = 0; k < kFingerCount; ++k)
    {
        const int b = aFingers[static_cast<size_t>(k)];
        aR.prevF[static_cast<size_t>(k)] = b >= 0 && b < aIo.n ? aIo.b[b].r : Quat{};
    }
    aR.prevValid = math::IsFinite(aR.prevT) && math::IsFinite(aR.prevR);
    return left;
}

// Finger locals toward the game's grip of the weapon (normalized lerp, sign aligned by Nlerp). Fingers are leaves under LeftHand:
// hand, arm and weapon transforms are untouched. Weight 0 = pose bit for bit.
inline void ApplyFingers(ov::Pose& aPose, const FingerBones& aBones, const Entry& aE, float aW)
{
    const float w = ov::Clamp01(aW);
    if (!(w > ov::kZeroWeight))
        return;
    for (int k = 0; k < kFingerCount; ++k)
    {
        const int b = aBones[k];
        if (b < 0 || b >= aPose.n)
            continue;
        aPose.b[b].r = w >= 1.0f ? aE.fingers[k] : ov::Nlerp(aPose.b[b].r, aE.fingers[k], w);
    }
}

// Stock contact -> shoulder pocket along the barrel on the pose as it is (m, + = stock in front of the shoulder; NaN = no stock contact).
inline float StockGap(const ov::Skeleton& aSk, const ov::Pose& aPose, const gik::Rig& aRig, int aPocketBone, const Pocket& aPocket,
                      const Entry& aE)
{
    if (!(aE.stockY < 0.0f) || aPocketBone < 0 || aPocketBone >= aSk.n || !aRig.Valid(aSk))
        return std::numeric_limits<float>::quiet_NaN();
    Quat rw, rp;
    Vec3 pw, pp;
    gik::ModelOf(aSk, aPose, aRig.weaponRight, rw, pw);
    gik::ModelOf(aSk, aPose, aPocketBone, rp, pp);
    return math::Dot(pw - (pp + math::QuatRotate(rp, aPocket.local)), math::QuatRotate(rw, Vec3{0.0f, 1.0f, 0.0f})) + aE.stockY;
}
// Stock bound (m): the stock pass weapons keep |gap| <= this on the shoulder (utpp_supportgrip_test (2) / (2c)); the reach shift may slide
// the butt behind the pocket only this far (review round 5, 2026-11-10: Masamune / Ajax / Saratoga), the rest of the reach goes to the
// reach-limited grip weight.
inline constexpr float kStockGapTolerance = 0.005f;

struct StockResult
{
    bool applied = false;
    float gap = 0.0f;   // stock contact -> pocket along the barrel before the pass (m, + = stock in front of the shoulder)
    float shift = 0.0f; // weapon move along the barrel actually applied (m, < 0 = back toward the shoulder)
};

// Stock to shoulder: slides the weapon along its own barrel axis (aim direction and the right-hand grip on the weapon unchanged) until the
// stock contact point stockY meets the shoulder pocket, by moving RightHand with the right-arm two-bone IK (hand rotation kept).
// Request clamped to [-kMaxStockPush, kMaxStockPull]; aW scales the move (0 = pose bit for bit). The left hand is not touched here:
// the grip IK that runs after it follows the moved weapon.
inline bool ApplyStock(const ov::Skeleton& aSk, ov::Pose& aIo, const gik::Rig& aRig, int aPocketBone, const Pocket& aPocket,
                       const Entry& aE, float aW, const gik::Params& aP, StockResult& aOut)
{
    aOut = StockResult{};
    const float w = ov::Clamp01(aW);
    if (!(aE.stockY < 0.0f) || aPocketBone < 0 || aPocketBone >= aSk.n || !aRig.Valid(aSk))
        return false;
    Quat rw, rp, rh;
    Vec3 pw, pp, ph;
    gik::ModelOf(aSk, aIo, aRig.weaponRight, rw, pw);
    gik::ModelOf(aSk, aIo, aPocketBone, rp, pp);
    const Vec3 pocket = pp + math::QuatRotate(rp, aPocket.local);
    const Vec3 axis = math::QuatRotate(rw, Vec3{0.0f, 1.0f, 0.0f});
    const float gap = math::Dot(pw - pocket, axis) + aE.stockY;
    if (!std::isfinite(gap))
        return false;
    aOut.gap = gap;
    const float want = -std::fmin(kMaxStockPull, std::fmax(-kMaxStockPush, gap)) * w;
    if (!(std::fabs(want) > 1e-6f))
        return true;
    gik::ModelOf(aSk, aIo, aRig.right.hand, rh, ph);
    const Vec3 start = ph;
    ov::Pose& io = aIo;
    const ov::Xf keep[3] = {io.b[aRig.right.upper], io.b[aRig.right.lower], io.b[aRig.right.hand]};
    // The pocket rides on RightArm, which the right-arm IK itself turns: 3 fixed-point passes on the remaining gap (each ~1/5 of the
    // previous one, offline), total move along the barrel inside the same clamp.
    float total = 0.0f;
    for (int pass = 0; pass < 3; ++pass)
    {
        float step = want;
        if (pass > 0)
        {
            gik::ModelOf(aSk, io, aRig.weaponRight, rw, pw);
            gik::ModelOf(aSk, io, aPocketBone, rp, pp);
            const float g = math::Dot(pw - (pp + math::QuatRotate(rp, aPocket.local)), axis) + aE.stockY;
            // goal: the gap left = the first gap - w x its clamped part (w < 1 while the route fades in / out). Review round 5: was
            // (1 - w) x the clamped gap, which asked for the full 12 cm pull at any weight once the butt was further than the clamp from
            // the shoulder (an overlay switch into Rifle Aim: 12 cm weapon jump at w 0.003); identical inside the clamp.
            const float left = gap - w * std::fmin(kMaxStockPull, std::fmax(-kMaxStockPush, gap));
            step = std::isfinite(g) ? -(g - left) : 0.0f;
            step = std::fmax(-kMaxStockPull, std::fmin(kMaxStockPush, total + step)) - total;
            if (!(std::fabs(step) > 1e-4f))
                break;
        }
        gik::Result r;
        if (!gik::SolveArm(aSk, io, aRig.right, start + axis * (total + step), &rh, 1.0f, aP, r) || !r.ok || r.handErr > 0.002f)
        {
            if (pass > 0)
                break; // keep the earlier passes
            io.b[aRig.right.upper] = keep[0];
            io.b[aRig.right.lower] = keep[1];
            io.b[aRig.right.hand] = keep[2];
            return false;
        }
        total += step;
    }
    aOut.applied = true;
    aOut.shift = total;
    return true;
}
