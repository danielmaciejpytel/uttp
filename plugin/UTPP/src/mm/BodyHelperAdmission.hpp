#pragma once
// Pure admission rules for runtime helper writes. No I/O, no game types.
//
// A helper bundle (program.ir + binding.dat) may write bone records in APPLY mode only when the SHA-256 of both exact
// files and the declared output counts match an entry compiled into the DLL. mode.txt only selects OFF / PROBE / APPLY;
// it never authorises a bundle. A bundle without an entry (for example the first, woman-rig candidate) can only be
// loaded in PROBE (computes a proposal, writes nothing). One bundle per body: the table has one entry for the man and one
// for the woman; each is admitted on its own.
//
// Approval means: generated by tools/analysis/export_player_helper_bundle.py from the player's own deformer graph of
// that body, reproduced the engine's helper records on raw engine poses within the recorded tolerance, and matched the
// offline reference on recorded frames (tests/BodyHelperBundleTest.cpp). The numeric body id is the one used by the
// motion driver pose snapshot (0 = woman, 1 = man).
