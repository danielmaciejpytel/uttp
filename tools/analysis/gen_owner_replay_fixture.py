"""Generates plugin/UTPP/tests/data/recording_1215_owner_replay.inc for tests/CameraTargetRootTest.cpp (rest TIP owner rule, recording 2026-10-21 12:15).

Window: video 90.6-93.0 s, the P4 episode 3 (ADS shot at 91.07 s, RMB released 91.37 s, hipfire lease and pose hold until ~92.2 s, the
capsule turned from 131 to -123 deg at 91.5-92.15 s, reload at 94.985 s). Sampled at 60 Hz: capsule yaw relative to the first sample
(the host starts aligned), ADS (UpperBody 6) and Shoot (action 8).

Usage: python -I gen_owner_replay_fixture.py <rec1215 dir with pose.npz, clockmap.py, common.py> <out .inc>
"""
import sys

HERE = sys.argv[1].replace('\\', '/').rstrip('/') + '/'
OUT = sys.argv[2]
import os
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..', '..', 'Tools', 'pylibs'))
sys.path.insert(0, HERE)
import numpy as np
from common import feed_arrays, ci, wrap

Z = np.load(HERE + 'pose.npz', allow_pickle=True)
meta = Z['meta']
t = meta[:, 0]
act = meta[:, 3].astype(int)
aim = meta[:, 4].astype(int)
cols, F = feed_arrays()
yaw = ci(t, F['t'], F['yawDeg'])
V0 = 91.560
grid = V0 + 90.6 + np.arange(0, int(round((93.0 - 90.6) * 60))) / 60.0
ug = np.degrees(np.unwrap(np.radians(yaw)))
rel = np.interp(grid, t, ug)
rel = rel - rel[0]
idx = np.clip(np.searchsorted(t, grid, side='right') - 1, 0, len(t) - 1)
with open(OUT, 'w', newline='\n') as f:
    f.write('// generated by tools/analysis/gen_owner_replay_fixture.py from the 2026-10-21 12:15 recording (video 90.6-93.0 s, 60 Hz)\n')
    f.write('// OwnerFrame = { capsule yaw relative to the first sample deg (unwrapped), ADS (UpperBody 6), Shoot (action 8) }\n')
    f.write('static const OwnerFrame kOwnerFrames[] = {\n')
    for k in range(len(grid)):
        f.write('    {%.2ff, %d, %d},\n' % (rel[k], int(aim[idx[k]] == 1), int(act[idx[k]] == 8)))
    f.write('};\n')
print('frames', len(grid), 'capsule travel %.1f deg' % (rel[-1] - rel[0]))
