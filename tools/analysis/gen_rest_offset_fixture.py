"""Generates plugin/UTPP/tests/data/recording_1215_rest_offset.inc for tests/RestOffsetCollapseTest.cpp (P4 follow-up, recording 2026-10-21 12:15).

Every reload that starts with V standing (speed <= 0.3 m/s) and a hidden yaw offset |Hips s2 - s0| > 45 deg is one episode. The window
runs from the frame before the reload edge to the first ADS (UpperBody 6) / Shoot / movement (speed > 0.3 m/s) after the reload ended.
Per frame: dt, capsule yaw delta (feed yawDeg), flags (1 reload upper weight > 0, 2 ADS, 4 moving). Per episode: the measured offset
before the reload, the capsule yaw and camera yaw at the event, the event kind (1 ADS, 2 shot, 3 move) and the visible-body-to-camera
angle of the pre-change build (offset released at the reload edge, measured at the event).

Usage: python -I gen_rest_offset_fixture.py <rec1215 dir with pose.npz, clockmap.py, common.py> <out .inc>
"""
import sys

HERE = sys.argv[1].replace('\\', '/').rstrip('/') + '/'
OUT = sys.argv[2]
import os
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..', '..', 'Tools', 'pylibs'))
sys.path.insert(0, HERE)
import numpy as np
from common import feed_arrays, ci, wrap

Z = np.load(HERE + 'pose.npz', allow_pickle=True)
meta = Z['meta']
d = Z['d']
t = meta[:, 0]
act = meta[:, 3].astype(int)
aim = meta[:, 4].astype(int)
up = meta[:, 6]
cols, F = feed_arrays()
ft = F['t']
yaw = ci(t, ft, F['yawDeg'])
cam = ci(t, ft, F['camDeg'])
vx = np.interp(t, ft, np.nan_to_num(F['vx']))
vy = np.interp(t, ft, np.nan_to_num(F['vy']))
sp = np.hypot(vx, vy)


def qyaw(q):
    x, y, z, w = q[..., 0], q[..., 1], q[..., 2], q[..., 3]
    return np.degrees(np.arctan2(-(2 * (x * y - w * z)), 1 - 2 * (x * x + z * z)))


off = wrap(qyaw(d[:, 2, 1, 3:7].astype(np.float64)) - qyaw(d[:, 0, 1, 3:7].astype(np.float64)))
V0 = 91.560
EV = {'ADS': 1, 'shot': 2, 'move': 3}
frames = []
eps = []
for k in range(1, len(t)):
    if not (act[k] == 2 and act[k - 1] != 2):
        continue
    if abs(off[k - 1]) < 45 or sp[k] > 0.3:
        continue
    e = k
    while e < len(t) and (act[e] == 2 or (1 - up[e]) > 0.02):
        e += 1
    ev, i = None, e
    for i in range(e, min(len(t), e + 2000)):
        if sp[i] > 0.3:
            ev = 'move'
            break
        if aim[i] == 1:
            ev = 'ADS'
            break
        if act[i] == 8:
            ev = 'shot'
            break
    if ev is None:
        continue
    first = len(frames)
    for j in range(k, i + 1):
        w = (1 - up[j]) > 0.02 or act[j] == 2
        flags = (1 if w else 0) | (2 if aim[j] == 1 else 0) | (4 if sp[j] > 0.3 else 0)
        frames.append((t[j] - t[j - 1], float(wrap(yaw[j] - yaw[j - 1])), flags))
    pre = abs(wrap(yaw[i] + off[i] - cam[i]))  # measured at the event in the recording (pre-change build)
    eps.append(('v%.3f' % (t[k] - V0), first, len(frames) - first, float(off[k - 1]), float(yaw[i]), float(cam[i]), EV[ev], float(pre),
                float(wrap(yaw[k - 1] + off[k - 1] - cam[i]))))

with open(OUT, 'w', newline='\n') as f:
    f.write('// generated by tools/analysis/gen_rest_offset_fixture.py from the 2026-10-21 12:15 recording (pose frame clock)\n')
    f.write('// RestFrame = { dt s, capsule yaw delta deg, flags 1 reload / 2 ADS / 4 moving }\n')
    f.write('static const RestFrame kRestFrames[] = {\n')
    for r in frames:
        f.write('    {%.5ff, %.2ff, %d},\n' % r)
    f.write('};\n')
    f.write('// RestEpisode = { reload edge (video s), first frame, count, offset before the reload deg, capsule yaw at the event deg,\n')
    f.write('//                 camera yaw at the event deg, event 1 ADS / 2 shot / 3 move, pre-change visible-to-camera deg,\n')
    f.write('//                 visible-to-camera deg if the offset were carried unchanged }\n')
    f.write('static const RestEpisode kRestEpisodes[] = {\n')
    for e in eps:
        f.write('    {"%s", %d, %d, %.2ff, %.2ff, %.2ff, %d, %.1ff, %.1ff},\n' % e)
    f.write('};\n')
print('episodes', len(eps), 'frames', len(frames))
for e in eps:
    print(e[0], 'frames', e[2], 'offset %.0f' % e[3], 'event', e[6], 'dur %.2f' % sum(fr[0] for fr in frames[e[1]:e[1] + e[2]]))
