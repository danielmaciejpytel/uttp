"""Generates the recorded ADS-shot episodes used by tools/lua-tests/test_utpp_bodyturn.lua (P4, recording 2026-10-21 12:15).

For every episode the script prints one Lua table: the CET signals the executor sees (upper body = 6 while aiming, Shoot=8
window) and the camera yaw shown by utpp_camera (viewYaw), sampled on the pose-CSV frame clock (feed_t, s).

Usage: python -I gen_lua_ads_shot_fixture.py <rec1215 dir with pose.npz, clockmap.py, common.py> > fixture.lua.txt
The input directory is analysis output of the recording (not a repository asset); only the printed numbers are committed.
"""
import sys
import os

HERE = sys.argv[1].replace('\\', '/').rstrip('/') + '/'
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..', '..', 'Tools', 'pylibs'))
sys.path.insert(0, HERE)
import numpy as np
from common import feed_arrays, ci

Z = np.load(HERE + 'pose.npz', allow_pickle=True)
meta = Z['meta']
t = meta[:, 0]
act = meta[:, 3].astype(int)
aim = meta[:, 4].astype(int)
cols, F = feed_arrays()
ft = F['t']
cam = ci(t, ft, F['camDeg'])
yaw = ci(t, ft, F['yawDeg'])
VIDEO_MINUS_FEED = 91.560

# (video second of the Shoot=8 start, label). All three: aimed shot, RMB released 0.0-0.13 s before the Shoot=8 flag drops,
# then the camera is turned 150-250 deg while V stands (stick 0).
EPISODES = [(81.418, 'v81.4'), (85.219, 'v85.2'), (91.068, 'v91.1')]


def run_end(i0, arr, value):
    j = i0
    while j + 1 < len(arr) and arr[j + 1] == value:
        j += 1
    return j


print('-- generated by tools/analysis/gen_lua_ads_shot_fixture.py from the 2026-10-21 12:15 recording (pose frame clock)')
print('-- fields: name; body0 = capsule yaw (deg) at the first sample; adsOn/adsOff = upperBody==6 window; shot0/shot1 = Shoot=8 window')
print('-- (s from the first sample); cam = {t0, yaw0, t1, yaw1, ...} camera yaw shown (deg), t in s from the first sample')
print('local P4_ADS_SHOTS = {')
for video, label in EPISODES:
    i_shot = int(np.searchsorted(t, video + VIDEO_MINUS_FEED))
    j_shot = run_end(i_shot, act, 8)
    # ADS window containing the shot
    a0 = i_shot
    while a0 > 0 and aim[a0 - 1] == 1:
        a0 -= 1
    a1 = run_end(i_shot, aim, 1)
    start = max(0, a0 - 6)
    end = int(np.searchsorted(t, t[j_shot] + 1.6))
    t0 = t[start]
    flat = []
    for k in range(start, end):
        flat += ['%.3f' % (t[k] - t0), '%.1f' % cam[k]]
    print('  { name = "%s", body0 = %.1f, adsOn = %.3f, adsOff = %.3f, shot0 = %.3f, shot1 = %.3f,' % (
        label, yaw[start], t[a0] - t0, t[a1 + 1] - t0, t[i_shot] - t0, t[j_shot + 1] - t0))
    print('    cam = {' + ','.join(flat) + '} },')
print('}')
