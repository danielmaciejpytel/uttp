"""Rifle grip + stock 2026-11-10 - prints the generated data block of src/mm/SupportGrip.hpp (kTable) from the game's own player weapon
poses (grip_game.json of gripstock_extract.py: Female V pwa_w_* idlepose_shoulder frame 0; Male V pma_w_* gives the same weapon-frame
grip to 0.1 mm) and the stock calibration (stock_calib.json of gripstock_stock_calib.py, optional).
  python -I gripstock_make_table.py           -> stdout
  python -I gripstock_make_table.py --write   -> replaces the GENERATED TABLE / POCKET blocks of src/mm/SupportGrip.hpp
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import gripstock_extract as E  # noqa: E402

NL = chr(10)
# reach-shift cap per weapon (m; SupportGrip.hpp kMaxReachShift = 0.03); design choice: Hercules 10 cm (needs 8.4 F / 9.2 M)
MAX_SHIFT = {'hercules': 0.10, 'copperhead': 0.04}  # copperhead: hand priority (option A) needs <= 3.8 cm (M Ready)
MAX_SHIFT_DEFAULT = 0.03
# hand priority over the stock contact (no stock pass); design choice, option A: Copperhead (its long butt and the handguard
# cannot both be met by the overlay pose: the butt sits ~4 cm (F) / ~5.5 cm (M) behind the shoulder point, <= 1 cm in the arm skin)
HAND_FIRST = ('copperhead',)


def lines():
    out = []
    d = json.load(open(os.path.join(E.WORK, 'grip_game.json')))
    sc_path = os.path.join(E.WORK, 'stock_calib.json')
    sc = json.load(open(sc_path)) if os.path.exists(sc_path) else {}
    out.append('// GENERATED by Source/tools/films/gripstock_make_table.py - do not edit by hand')
    out.append('inline constexpr Entry kTable[] = {')
    for pid, fam, key in E.FAMILIES:
        r = d.get('woman:%s:idlepose_shoulder' % fam)
        m = d.get('man:%s:idlepose_shoulder' % fam)
        if r is None:
            continue
        assert m is None or max(abs(a - b) for a, b in zip(r['left_t'], m['left_t'])) < 1e-3, fam
        t, q = r['left_t'], r['left_q']
        fing = ', '.join('{%.6ff, %.6ff, %.6ff, %.6ff}' % tuple(r['fingers'][n]) for n in E.FINGERS)
        stock = sc.get(fam, {}).get('contact_y', 0.0)
        out.append('    // %s (%s idlepose_shoulder)' % (fam, os.path.basename(r['file'])))
        out.append('    {%d, "%s", {%.5ff, %.5ff, %.5ff}, {%.6ff, %.6ff, %.6ff, %.6ff},' % (pid, fam, t[0], t[1], t[2], q[0], q[1], q[2], q[3]))
        out.append('     {%s},' % fing)
        out.append('     %.5ff, %.5ff, %s},' % (stock, MAX_SHIFT.get(fam, MAX_SHIFT_DEFAULT), 'true' if fam in HAND_FIRST else 'false'))
    out.append('};')
    pk = []
    for body, name in (('woman', 'kPocketWoman'), ('man', 'kPocketMan')):
        p = sc.get('pocket_' + body)
        if p:
            assert p['bone'] == 'RightArm', p
            pk.append('inline constexpr Pocket %s{{%.5ff, %.5ff, %.5ff}}; // residual std %.2f cm (stock_calib.json)' % (
                name, p['local'][0], p['local'][1], p['local'][2], p['resid_std_cm']))
        else:
            pk.append('inline constexpr Pocket %s{{0.0f, 0.0f, 0.0f}}; // not calibrated' % name)
    return out, pk


def main():
    tab, pk = lines()
    if '--write' not in sys.argv:
        print(NL.join(tab + pk))
        return
    hp = os.path.join(E.WC.ROOT, 'Source', 'plugin', 'UTPP', 'src', 'mm', 'SupportGrip.hpp')
    s = open(hp, encoding='utf-8').read()
    for a, b, body in (('// ---- GENERATED TABLE BEGIN ----' + NL, '// ---- GENERATED TABLE END ----', tab),
                       ('// ---- GENERATED POCKET BEGIN ----' + NL, '// ---- GENERATED POCKET END ----', pk)):
        i, j = s.index(a) + len(a), s.index(b)
        s = s[:i] + NL.join(body) + NL + s[j:]
    open(hp, 'w', encoding='utf-8', newline=NL).write(s)
    print('WROTE', hp)


if __name__ == '__main__':
    main()
