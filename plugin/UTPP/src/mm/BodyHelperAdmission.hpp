enum class Mode : uint32_t { Off, Probe, Apply };
enum class Decision : uint32_t { LoadOff, LoadProbe, LoadApply, RefuseApply };
struct Verdict
{
    Decision decision = Decision::LoadOff;
    int32_t body = kBodyNone;  // body the bundle is approved for; kBodyNone when not approved
    bool approved = false;
    uint32_t baseMinBones = 0;         // rig requirement of the approval (0 when not approved)
    uint32_t closureBones = 0;
    uint64_t closureFingerprint = 0;
};

inline const Approved* Find(std::span<const Approved> table, std::string_view programSha256, std::string_view bindingSha256,
                            uint32_t owned, uint32_t children)
{
    for (const auto& a : table)
        if (!a.programSha256.empty() && a.programSha256 == programSha256 && a.bindingSha256 == bindingSha256 &&
            a.owned == owned && a.children == children)
            return &a;
    return nullptr;
}

// Off never needs a bundle. Probe loads any structurally valid bundle but approves nothing. Apply needs an exact entry.
inline Verdict Admit(Mode mode, std::string_view programSha256, std::string_view bindingSha256, uint32_t owned, uint32_t children,
                     std::span<const Approved> table = std::span<const Approved>(kApproved))
{
    Verdict v;
    if (mode == Mode::Off) { v.decision = Decision::LoadOff; return v; }
    const Approved* entry = Find(table, programSha256, bindingSha256, owned, children);
    if (entry) { v.approved = true; v.body = entry->body; v.baseMinBones = entry->baseMinBones;
                    v.closureBones = entry->closureBones; v.closureFingerprint = entry->closureFingerprint; }
    if (mode == Mode::Probe) { v.decision = Decision::LoadProbe; return v; }
    v.decision = entry ? Decision::LoadApply : Decision::RefuseApply;
    return v;
}

// Which session owner may precede a helper commit. Mapping: the historical experiment path (unchanged). FK: the shipped
// default, accepted only for an approved bundle (the core write happens in the FK detour right before the helper commit).
inline bool OwnerAllows(bool ownerIsMapping, bool ownerIsFk, bool bundleApproved)
{ return ownerIsMapping || (ownerIsFk && bundleApproved); }

// The live body must be exactly the one the bundle was approved for. An unapproved (PROBE-only) bundle keeps the legacy
// woman expectation, so its behaviour is unchanged.
inline bool BodyMatches(bool bundleApproved, int32_t approvedBody, int32_t liveBody)
{ return liveBody == (bundleApproved ? approvedBody : kBodyWoman); }

// The merged rig being armed must fit an approved bundle: at least the 619-bone base (so the 294-bone loading rig is refused),
// and the closure of the bundle's bones (binding.dat CORE, OWNED, CHILD, ANCHOR plus ancestors) must have the approved signature.
// Extra bones elsewhere (hair, accessories, garment dangles) are fine. A verdict that is not approved has nothing to check
// (PROBE-only bundles never write); an entry with a zero count or fingerprint accepts no rig.
enum class RigCheck : uint32_t { Ok, TooFewBones, SignatureMismatch };
template <class Parent>
inline RigCheck CheckRig(const Verdict& v, std::span<const uint64_t> names, std::span<const Parent> parents,
                         std::span<const uint64_t> bundleBones, RigSignature* signature = nullptr)
{
    if (!v.approved) return RigCheck::Ok;
    if (v.baseMinBones == 0 || v.closureBones == 0 || v.closureFingerprint == 0 || names.size() != parents.size() ||
        names.size() < v.baseMinBones)
        return RigCheck::TooFewBones;
    const RigSignature sig = ComputeRigSignature<Parent>(names, parents, bundleBones);
    if (signature) *signature = sig;
    return sig.ok && sig.bones == v.closureBones && sig.fingerprint == v.closureFingerprint ? RigCheck::Ok : RigCheck::SignatureMismatch;
}

// Rejection reasons of the hot gate, in evaluation order (counters in the runtime use the same numbering).
enum class Reject : uint32_t { None, Ragdoll, Gate, Identity, Perspective, Receipt, Body, Count };
struct GateInputs
{
    bool ragdollGameOwned = false, enabled = true, fault = false, ownerOk = true, armed = true, mmActive = true;
    bool planPresent = true;  // an armed plan exists (a missing plan is an identity failure, not a gate failure)
    bool identityOk = true, perspectiveOk = true, receiptComplete = true, bodyOk = true;
};
inline Reject Gate(const GateInputs& g)
{
    if (g.ragdollGameOwned) return Reject::Ragdoll;
    if (!g.enabled || g.fault || !g.armed || !g.mmActive) return Reject::Gate;
    if (!g.planPresent) return Reject::Identity;
    if (!g.ownerOk) return Reject::Gate;
    if (!g.identityOk) return Reject::Identity;
    if (!g.perspectiveOk) return Reject::Perspective;
    if (!g.receiptComplete) return Reject::Receipt;
    if (!g.bodyOk) return Reject::Body;
    return Reject::None;
}

// Weight-0 writers (mm/CoreWriteRecord.hpp kZeroWriterMask). The FK detour opens a window (kZeroWindow) only while the switch is on
// and one of them can write with the body shown in third person. Route of one player FK call:
//   Published      no window, or the published pose (driver / host) was written in the call: the path above, unchanged;
//   ZeroWritten    a weight-0 writer wrote core bones and no published pose: recompute, keeping the engine's own deviation from the
//                  graph (mm/BodyHelperCarry.hpp);
//   ZeroReference  inside the window, no layer wrote: the engine's deviation is measured; written only while it fades back after a run.
enum class Route : uint32_t { Published, ZeroWritten, ZeroReference };
inline Route RouteOf(uint32_t aRecord, bool aSwitchOn)
{
    namespace cw = corewrite;
    if (!aSwitchOn || !(aRecord & cw::kZeroWindow) || (aRecord & cw::kPublishedMask))
        return Route::Published;
    return (aRecord & cw::kZeroWriterMask) ? Route::ZeroWritten : Route::ZeroReference;
}
// The hot gate inputs of a zero route: the window replaces the motion-active requirement (these writers run at motion weight 0), and
// the perspective is passed when the camera permission allows writes or the vehicle camera shows the third-person body.
inline void ZeroRouteInputs(GateInputs& g, bool aPerspectiveWriteAllows, uint32_t aRecord)
{
    g.mmActive = true;
    g.perspectiveOk = aPerspectiveWriteAllows || (aRecord & corewrite::kVehicleThirdPerson) != 0;
}
// The published pose snapshot identifies the body. The published path also needs a positive weight; a zero route only a fresh snapshot
// of the same rig (the weight is 0 there by definition).
inline bool SnapshotUsable(Route aRoute, bool aRead, bool aRigMatches, float aWeight, bool aFresh)
{
    return aRead && aRigMatches && aFresh && (aRoute != Route::Published || aWeight > 0.0f);
}
// The carried offset may be used on a written frame only when it was measured for the same plan and body within aMaxAge ticks.
inline bool ReferenceUsable(bool aValid, bool aSamePlan, int64_t aUpdated, int64_t aNow, int64_t aMaxAge)
{
    return aValid && aSamePlan && aUpdated > 0 && aNow >= aUpdated && aMaxAge > 0 && aNow - aUpdated <= aMaxAge;
}
